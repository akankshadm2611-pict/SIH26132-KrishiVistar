export function getDistrictsForState(stateName: string): string[] {
  const stateData = locationHierarchy.find(
    (s) => s.state.toLowerCase() === stateName.trim().toLowerCase()
  );
  if (!stateData) return [];
  return stateData.districts.map((d) => d.name);
}

export function getTalukasForDistrict(stateName: string, districtName: string): string[] {
  const stateData = locationHierarchy.find(
    (s) => s.state.toLowerCase() === stateName.trim().toLowerCase()
  );
  if (!stateData) return [];

  // Match district
  const dist = stateData.districts.find(
    (d) =>
      d.name.toLowerCase() === districtName.trim().toLowerCase() ||
      districtName.toLowerCase().includes(d.name.toLowerCase()) ||
      d.name.toLowerCase().includes(districtName.toLowerCase())
  );
  if (dist) return dist.talukas;

  // Fallback: return all talukas in the state
  const allTalukas: string[] = [];
  stateData.districts.forEach((d) => allTalukas.push(...d.talukas));
  return Array.from(new Set(allTalukas));
}
